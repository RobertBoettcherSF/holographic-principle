#!/usr/bin/env python3
"""Embed the WebAssembly module and the version stamp into the Pages files.
usage: embed.py hp.wasm version.txt web/index.html web/tour.html
"""
import base64, pathlib, shutil, sys

wasm, version, index, tour = sys.argv[1:5]
root = pathlib.Path(__file__).resolve().parent.parent
stamp = pathlib.Path(version).read_text().strip()
b64 = base64.b64encode(pathlib.Path(wasm).read_bytes()).decode()
ada = """// Generated by build.sh. Logic lives in src/ and is compiled to WebAssembly.
export const VERSION = %s;
const WASM_BASE64 = "%s";
export async function loadAda() {
  const bytes = Uint8Array.from(atob(WASM_BASE64), c => c.charCodeAt(0));
  const {instance} = await WebAssembly.instantiate(bytes);
  const e = instance.exports;
  const inputs = e.hp_inputs() >>> 0;
  const outputs = e.hp_outputs() >>> 0;
  const geom = e.hp_geom() >>> 0;
  const geomI = e.hp_geom_i() >>> 0;
  const view = (ptr, Ctor, n) => new Ctor(e.memory.buffer, ptr, n);
  return {
    memory: e.memory,
    compute(card) { e.hp_compute(card); },
    tick() { e.hp_tick(); },
    inputs: () => view(inputs, Float64Array, 16),
    outputs: () => view(outputs, Float64Array, 32),
    geom: () => view(geom, Float64Array, 8192),
    geomI: () => view(geomI, Int32Array, 1024)
  };
}
""" % (repr(stamp), b64)
(root / "ada.js").write_text(ada)
for src in (index, tour):
    text = pathlib.Path(src).read_text().replace("__VERSION_STAMP__", stamp)
    name = pathlib.Path(src).name
    (root / name).write_text(text)
for name in ("styles.css", "i18n.js", "sounds.js", "session.js", "splash.js", "tour.js"):
    shutil.copyfile(root / "web" / name, root / name)
print("stamp", stamp)
